/** Fabric API: entities/players moving between dimensions (server) (Omniloader stand-in; generated by tools/gen-fabric-events.py). */
public final class ServerEntityWorldChangeEvents {
    private ServerEntityWorldChangeEvents() {}

    public static final Event<AfterEntityChange> AFTER_ENTITY_CHANGE_WORLD = EventFactory.createArrayBacked(AfterEntityChange.class, ls -> (originalEntity, newEntity, origin, destination) -> { for (AfterEntityChange l : ls) l.afterChangeWorld(originalEntity, newEntity, origin, destination); });
    public static final Event<AfterPlayerChange> AFTER_PLAYER_CHANGE_WORLD = EventFactory.createArrayBacked(AfterPlayerChange.class, ls -> (player, origin, destination) -> { for (AfterPlayerChange l : ls) l.afterChangeWorld(player, origin, destination); });

    @FunctionalInterface public interface AfterEntityChange { void afterChangeWorld(Entity originalEntity, Entity newEntity, ServerLevel origin, ServerLevel destination); }
    @FunctionalInterface public interface AfterPlayerChange { void afterChangeWorld(ServerPlayer player, ServerLevel origin, ServerLevel destination); }
}
