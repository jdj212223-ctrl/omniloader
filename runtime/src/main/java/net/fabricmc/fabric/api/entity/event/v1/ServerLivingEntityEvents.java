/** Fabric API: mobs taking damage and dying (server) (Omniloader stand-in; generated by tools/gen-fabric-events.py). */
public final class ServerLivingEntityEvents {
    private ServerLivingEntityEvents() {}

    public static final Event<AllowDamage> ALLOW_DAMAGE = EventFactory.createArrayBacked(AllowDamage.class, ls -> (entity, source, amount) -> { for (AllowDamage l : ls) if (!l.allowDamage(entity, source, amount)) return false; return true; });
    public static final Event<AfterDamage> AFTER_DAMAGE = EventFactory.createArrayBacked(AfterDamage.class, ls -> (entity, source, baseDamageTaken, damageTaken, blocked) -> { for (AfterDamage l : ls) l.afterDamage(entity, source, baseDamageTaken, damageTaken, blocked); });
    public static final Event<AllowDeath> ALLOW_DEATH = EventFactory.createArrayBacked(AllowDeath.class, ls -> (entity, damageSource, damageAmount) -> { for (AllowDeath l : ls) if (!l.allowDeath(entity, damageSource, damageAmount)) return false; return true; });
    public static final Event<AfterDeath> AFTER_DEATH = EventFactory.createArrayBacked(AfterDeath.class, ls -> (entity, damageSource) -> { for (AfterDeath l : ls) l.afterDeath(entity, damageSource); });
    public static final Event<MobConversion> MOB_CONVERSION = EventFactory.createArrayBacked(MobConversion.class, ls -> (previous, converted, keepEquipment) -> { for (MobConversion l : ls) l.onConversion(previous, converted, keepEquipment); });

    @FunctionalInterface public interface AllowDamage { boolean allowDamage(LivingEntity entity, DamageSource source, float amount); }
    @FunctionalInterface public interface AfterDamage { void afterDamage(LivingEntity entity, DamageSource source, float baseDamageTaken, float damageTaken, boolean blocked); }
    @FunctionalInterface public interface AllowDeath { boolean allowDeath(LivingEntity entity, DamageSource damageSource, float damageAmount); }
    @FunctionalInterface public interface AfterDeath { void afterDeath(LivingEntity entity, DamageSource damageSource); }
    @FunctionalInterface public interface MobConversion { void onConversion(Mob previous, Mob converted, boolean keepEquipment); }
}
