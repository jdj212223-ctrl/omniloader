/** Fabric API: player join/leave/respawn (server) (Omniloader stand-in; generated by tools/gen-fabric-events.py). */
public final class ServerPlayerEvents {
    private ServerPlayerEvents() {}

    public static final Event<CopyFrom> COPY_FROM = EventFactory.createArrayBacked(CopyFrom.class, ls -> (oldPlayer, newPlayer, alive) -> { for (CopyFrom l : ls) l.copyFromPlayer(oldPlayer, newPlayer, alive); });
    public static final Event<AfterRespawn> AFTER_RESPAWN = EventFactory.createArrayBacked(AfterRespawn.class, ls -> (oldPlayer, newPlayer, alive) -> { for (AfterRespawn l : ls) l.afterRespawn(oldPlayer, newPlayer, alive); });
    public static final Event<Join> JOIN = EventFactory.createArrayBacked(Join.class, ls -> player -> { for (Join l : ls) l.onJoin(player); });
    public static final Event<Leave> LEAVE = EventFactory.createArrayBacked(Leave.class, ls -> player -> { for (Leave l : ls) l.onLeave(player); });
    public static final Event<AllowDeath> ALLOW_DEATH = EventFactory.createArrayBacked(AllowDeath.class, ls -> (player, damageSource, damageAmount) -> { for (AllowDeath l : ls) if (!l.allowDeath(player, damageSource, damageAmount)) return false; return true; });

    @FunctionalInterface public interface CopyFrom { void copyFromPlayer(ServerPlayer oldPlayer, ServerPlayer newPlayer, boolean alive); }
    @FunctionalInterface public interface AfterRespawn { void afterRespawn(ServerPlayer oldPlayer, ServerPlayer newPlayer, boolean alive); }
    @FunctionalInterface public interface Join { void onJoin(ServerPlayer player); }
    @FunctionalInterface public interface Leave { void onLeave(ServerPlayer player); }
    @FunctionalInterface public interface AllowDeath { boolean allowDeath(ServerPlayer player, DamageSource damageSource, float damageAmount); }
}
