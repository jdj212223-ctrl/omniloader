package dev.omniloader.loader.convert;

import dev.omniloader.loader.mapping.Mappings;

import java.util.LinkedHashMap;
import java.util.Map;

/** Turns a Fabric access widener into a NeoForge access transformer (same idea, different file format). */
public final class AccessWidenerConverter {
    private AccessWidenerConverter() {}

    private static final class Rule { int vis; boolean definal; }  // vis: 0 none, 1 protected, 2 public

    /**
     * Fields NeoForge itself rewrites into getter calls. Widening them breaks NeoForge's rewrite and crashes the game,
     * so those rules are dropped (the mod's reads are redirected to the getters instead, see {@link NeoFieldGetters}).
     */
    static boolean protectedByNeoForge(String owner, String field) {
        return NeoFieldGetters.GETTERS.containsKey(owner.replace('.', '/') + "." + field);
    }

    public static String convert(String aw, Mappings m) {
        Map<String, Rule> rules = new LinkedHashMap<>();
        for (String raw : aw.split("\n")) {
            String line = raw.contains("#") ? raw.substring(0, raw.indexOf('#')) : raw;
            String[] t = line.trim().split("\\s+");
            if (t.length < 3 || t[0].equals("accessWidener")) continue;
            String access = t[0].replace("transitive-", "");
            String kind = t[1];
            String owner = m.mapClass(t[2]).replace('/', '.');
            String target;
            switch (kind) {
                case "class" -> target = owner;
                case "method" -> target = owner + " " + m.mapMethod(t[3]) + m.mapText(t[4]);
                case "field" -> {
                    String f = m.mapField(t[3]);
                    if (protectedByNeoForge(owner, f)) continue;
                    target = owner + " " + f;
                }
                default -> { continue; }
            }
            Rule r = rules.computeIfAbsent(target, k -> new Rule());
            switch (access) {
                case "accessible" -> r.vis = 2;
                case "extendable" -> { r.vis = Math.max(r.vis, kind.equals("class") ? 2 : 1); r.definal = true; }
                case "mutable" -> { r.definal = true; r.vis = Math.max(r.vis, 2); }
                default -> {}
            }
        }
        StringBuilder sb = new StringBuilder("# Generated by Omniloader from a Fabric access widener\n");
        rules.forEach((target, r) -> sb.append(r.vis == 1 ? "protected" : "public").append(r.definal ? "-f " : " ").append(target).append('\n'));
        return sb.toString();
    }
}
